# news_handler3.py
from openai import OpenAI
import os
from dotenv import load_dotenv

load_dotenv()

client = OpenAI(
    api_key=os.getenv("PROXYAPI_KEY"),
    base_url="https://api.proxyapi.ru/openai/v1",  # ProxyAPI OpenAI-совместимый API [web:40]
)


async def analyze_news3(query: str) -> str:
    prompt = f"""Ты — ассистент-фактчекер Pravdorub. Твоя задача — проверить новость или утверждение на достоверность с помощью открытых источников.

Текст новости или утверждения для проверки:
\"\"\"{query}\"\"\"

ОЧЕНЬ ВАЖНО:

- ВСЕГДА исходи из того, что в новости МОЖЕТ БЫТЬ ОШИБКА, даже если общая идея верная.
- Твоя задача — НЕ подтверждать новость, а ИСКАТЬ В НЕЙ ОШИБКИ и ИСКАЖЕНИЯ (особенно в числах, датах, формулировках).
- Если новость в целом верно описывает ситуацию, но числа, даты или формулировки отличаются от авторитетных источников, НЕЛЬЗЯ ставить ОЦЕНКА: ФАКТ и НЕЛЬЗЯ рекомендовать "доверять".

Если текст начинается со слов "Новость по ссылке", считай, что:
- тебе дали краткое содержание статьи;
- ты должен сравнить это содержание с источниками и ЯВНО указать, совпадают ли числа, даты и формулировки.

ОЧЕНЬ СТРОГИЕ ПРАВИЛА ДЛЯ ЧИСЕЛ:

- Если числовые данные (количество людей, суммы, проценты, даты, возраст и т.п.) в новости и в надёжных источниках отличаются более чем на 3%, НЕЛЬЗЯ ставить ОЦЕНКУ: ФАКТ.
- В таких случаях используй ОЦЕНКА: НЕ СОВПАДАЮТ ЧИСЛА или СОМНИТЕЛЬНО.
- В РЕКОМЕНДАЦИИ при заметных расхождениях чисел НЕЛЬЗЯ писать просто "доверять". Используй "не совпадают числа" или "осторожно".
- ВСЕГДА явно указывай: какие числа указаны в новости и какие числа указаны в источниках.

ОТДЕЛЬНЫЕ ПРАВИЛА ДЛЯ ВОЗРАСТА ЛЮДЕЙ:

- Возраст человека (количество полных лет) НЕЛЬЗЯ округлять.
- Если в новости указан один возраст, а в источниках другой, это считается фактической ошибкой.
- В таких случаях НЕЛЬЗЯ ставить ОЦЕНКА: ФАКТ и НЕЛЬЗЯ рекомендовать "доверять".

ФОРМАТ ОТВЕТА (строго придерживайся):

1. ✅ ОЦЕНКА: ФАКТ / ФЕЙК / СОМНИТЕЛЬНО / НЕ СОВПАДАЮТ ЧИСЛА
2. КРАТКО: 2–3 предложения сути новости и итога проверки
3. ИСТОЧНИКИ: 2–3 ссылки на надёжные источники. ЕСЛИ НЕ МОЖЕШЬ УКАЗАТЬ НИ ОДНОЙ РЕАЛЬНОЙ ССЫЛКИ, НЕ СТАВЬ ОЦЕНКА: ФАКТ
ОЧЕНЬ ВАЖНО:
- ЕСЛИ ты не можешь указать НИ ОДНОЙ реальной ссылки, НЕЛЬЗЯ использовать ОЦЕНКА: ФАКТ и НЕЛЬЗЯ писать РЕКОМЕНДАЦИЯ: доверять.
- В таком случае используй ОЦЕНКА: СОМНИТЕЛЬНО или НЕ СОВПАДАЮТ ЧИСЛА и РЕКОМЕНДАЦИЯ: осторожно.
- ПУСТОЙ пункт "ИСТОЧНИКИ" считается ошибкой: ты обязан либо дать ссылки, либо понизить доверие к новости.
4. РЕКОМЕНДАЦИЯ: доверять / не доверять / осторожно / не совпадают числа

Форматируй ответ в markdown, будь предельно краток и по делу.
"""

    try:
        response = client.chat.completions.create(
            model="gpt-4o-mini-search-preview",  # модель с веб-поиском через ProxyAPI [web:46][web:78]
            messages=[{"role": "user", "content": prompt}],
            max_tokens=600,
            # ВАЖНО: без temperature — поисковые модели его не принимают [web:83][web:89]
        )
        result = response.choices[0].message.content

        return f"""📰 <b>Pravdorub: {query[:50]}...</b>

{result}

🧠 <b>Модель:</b> GPT через ProxyAPI"""
    except Exception as e:
        return f"""❌ <b>Ошибка API ProxyAPI/OpenAI</b>

Проверь PROXYAPI_KEY в .env

Тест фейка: "Илон Маск купил Telegram" = <b>ФЕЙК</b>
Детали: {str(e)}"""
